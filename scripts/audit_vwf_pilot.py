#!/usr/bin/env python3
"""Review downloaded primary records without silently promoting them to KG evidence.

Reads manifest and raw payloads generated by ingest_vwf_pilot.py.
Produces a machine-readable audit; does NOT change the public evidence snapshot.
"""
import argparse
import json
import hashlib
from pathlib import Path

TARGETS = {"R1315L": {"protein": "R1315L", "transcript": "NM_000552.5", "hgvs": "c.3944G>T"},
           "H1786D": {"protein": "H1786D", "transcript": None, "hgvs": None}}

def review(root):
    manifest = json.loads((root / "manifest.json").read_text())
    findings = []
    for entry in manifest["records"]:
        variant = entry["variant"]
        if entry.get("status") != "retrieved_not_adjudicated":
            findings.append({"variant": variant, "provider": entry.get("provider"), "status": entry["status"],
                             "promotion_allowed": False})
            continue
        # Use the expected basename, never an arbitrary manifest-supplied path.
        raw_path = root / (variant + "_" + entry["provider"] + ".json")
        if not raw_path.is_file():
            findings.append({"variant": variant, "provider": entry.get("provider"),
                             "status": "raw_record_missing", "promotion_allowed": False})
            continue
        payload = raw_path.read_bytes()
        if hashlib.sha256(payload).hexdigest() != entry.get("sha256"):
            findings.append({"variant": variant, "provider": entry.get("provider"),
                             "status": "checksum_mismatch", "promotion_allowed": False})
            continue
        try:
            raw = json.loads(payload)
        except (ValueError, UnicodeDecodeError):
            findings.append({"variant": variant, "provider": entry.get("provider"),
                             "status": "invalid_source_json", "promotion_allowed": False})
            continue
        provider = entry["provider"]
        if provider == "clinvar_discovery":
            ids = raw.get("esearchresult", {}).get("idlist", [])
            findings.append({"variant": variant, "provider": provider,
                             "status": "candidate_ids_require_identity_review",
                             "candidate_count": len(ids),
                             "candidate_ids": [str(x) for x in ids[:25]],
                             "promotion_allowed": False,
                             "review_required": ["confirm_VWF_gene", "protein_HGVS",
                                                 "transcript_HGVS", "GRCh38_REF_ALT",
                                                 "clinical_review_status"]})
        elif provider == "clinvar_candidates":
            result = raw.get("result", {}) if isinstance(raw, dict) else {}
            ids = [str(x) for x in result.get("uids", [])]
            summaries = [result.get(cid, {}) for cid in ids]
            valid_ids = bool(ids) and all(str(item.get("uid", "")) == cid for cid, item in zip(ids, summaries))
            # Text matches in ClinVar are only search hits, never allele-level proof.
            findings.append({"variant": variant, "provider": provider,
                             "status": "candidate_summaries_retrieved" if valid_ids else "candidate_summaries_invalid",
                             "candidate_count": len(ids),
                             "candidate_ids": ids,
                             "promotion_allowed": False,
                             "review_required": ["VWF_gene_identity", "protein_HGVS",
                                                 "transcript_HGVS", "GRCh38_REF_ALT",
                                                 "clinical_assertion_review_status"]})
        elif provider == "clinvar":
            cid = "100312" if variant == "R1315L" else None
            summary = raw.get("result", {}).get(cid, {}) if cid else {}
            # An ID match does not verify the clinical significance, coordinates, or mapping.
            ok = bool(summary and str(summary.get("uid", "")) == cid)
            findings.append({"variant": variant, "provider": provider, "status": "identifier_verified" if ok else "identifier_unverified",
                             "record_id": cid, "promotion_allowed": False,
                             "review_required": ["clinical_assertion_and_review_status", "GRCh38_reference_allele",
                                                 "transcript_and_protein_HGVS", "source_release"]})
        elif provider == "ensembl":
            target = TARGETS[variant]
            matches = []
            for record in raw if isinstance(raw, list) else []:
                transcript_hits = []
                for consequence in record.get("transcript_consequences", []):
                    if consequence.get("gene_symbol") != "VWF":
                        continue
                    protein = str(consequence.get("amino_acids", ""))
                    position = str(consequence.get("protein_start", ""))
                    if target["protein"] == "R1315L" and position == "1315" and protein in ("R/L", "Arg/Leu"):
                        transcript_hits.append({"transcript_id": consequence.get("transcript_id"),
                                                "protein_start": position, "amino_acids": protein})
                if transcript_hits:
                    matches.append({"input": record.get("input"), "assembly_name": record.get("assembly_name"),
                                    "seq_region_name": record.get("seq_region_name"), "start": record.get("start"),
                                    "allele_string": record.get("allele_string"), "transcripts": transcript_hits})
            findings.append({"variant": variant, "provider": provider,
                             "status": "protein_consequence_candidate" if matches else "no_matching_protein_consequence",
                             "matches": matches, "promotion_allowed": False,
                             "review_required": ["transcript_version", "genome_assembly", "reference_allele",
                                                 "independent_ClinVar_concordance"]})
    # Compare independently retrieved sources without inferring concordance from
    # a shared protein label alone. Clinical and population assertions stay separate.
    reconciliation = []
    for variant in TARGETS:
        group = [f for f in findings if f["variant"] == variant]
        clinvar = next((f for f in group if f.get("provider") == "clinvar"), None)
        discovery = next((f for f in group if f.get("provider") == "clinvar_discovery"), None)
        ensembl = next((f for f in group if f.get("provider") == "ensembl"), None)
        if discovery and not clinvar:
            status = "candidate_discovery_not_allele_verified"
        elif not clinvar or not ensembl:
            status = "insufficient_primary_sources"
        elif clinvar["status"] != "identifier_verified":
            status = "clinvar_identifier_unverified"
        elif ensembl["status"] != "protein_consequence_candidate":
            status = "ensembl_protein_consequence_unverified"
        else:
            status = "partial_concordance_requires_allele_and_transcript_review"
        reconciliation.append({"variant": variant, "status": status,
                               "clinical_classification_verified": False,
                               "population_frequency_verified": False,
                               "promotion_allowed": False})
    return {"audit_schema": "vwf-source-audit/0.1", "findings": findings,
            "reconciliation": reconciliation,
            "promotion_policy": "Human or separately validated automatic review required; no source record automatically modifies data/multisource-evidence.json."}

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--raw-dir", default="data/pilot_raw")
    args = p.parse_args()
    root = Path(args.raw_dir)
    report = review(root)
    (root / "audit.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"findings": len(report["findings"]), "promoted": 0, "output": str(root / "audit.json")}))
if __name__ == "__main__":
    main()
